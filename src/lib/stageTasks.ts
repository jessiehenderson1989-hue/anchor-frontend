export const flattenTasks = (groups: TaskGroup[]): string[] => groups.flatMap(gr => gr.items)

// Index of the first step in each group, mapped to that group's title
export const groupStarts = (groups: TaskGroup[]): Record<number, string> => {
  const out: Record<number, string> = {}
  let i = 0
  for (const gr of groups) { out[i] = gr.title; i += gr.items.length }
  return out
}
